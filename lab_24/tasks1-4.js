// Чекаємо повного завантаження DOM-дерева
$(document).ready(function() {

    // ================= ЗАВДАННЯ 1 =================
    // Шукаємо всі теги <a>, атрибут href яких починається (^) на "https://"
    // та додаємо їм атрибут target зі значенням "_blank"
    $('a[href^="https://"]').attr('target', '_blank');


    // ================= ЗАВДАННЯ 2 =================
    // 1. Знаходимо всі <h2> з класом head
    let $headElements = $('h2.head');
    
    // 2. Робимо для них зелений колір фону
    $headElements.css('background-color', 'lightgreen'); // Використав світло-зелений, щоб текст було видно
    
    // 3. Серед ЗНАЙДЕНИХ елементів шукаємо ті, що мають клас inner і міняємо розмір шрифту
    $headElements.find('.inner').css('font-size', '35px');


    // ================= ЗАВДАННЯ 3 =================
    // Шукаємо всі <h3> всередині контейнера.
    // За допомогою .each() проходимось по кожному знайденому <h3>.
    $('#task3-container h3').each(function() {
        // $(this) - це поточний тег <h3>
        // .next('div') - беремо <div>, який стоїть одразу після нього
        // .insertBefore($(this)) - переміщуємо знайдений <div> ПЕРЕД поточним <h3>
        $(this).next('div').insertBefore($(this));
    });


    // ================= ЗАВДАННЯ 4 =================
    // Зберігаємо всі чекбокси у змінну
    let $checkboxes = $('.task4-checkbox');

    // Вішаємо обробник події 'change' (коли стан чекбокса змінюється)
    $checkboxes.on('change', function() {
        // Рахуємо кількість вибраних чекбоксів (псевдоклас :checked в jQuery)
        let checkedCount = $('.task4-checkbox:checked').length;

        // Якщо вибрано рівно 3
        if (checkedCount === 3) {
            // Робимо всі чекбокси неактивними
            $checkboxes.prop('disabled', true);
        }
    });

});