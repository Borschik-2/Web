// Функція для валідації номера картки
function validateCard(cardNumber) {
    // Регулярний вираз:
    // ^      - початок рядка
    // [45]   - перший символ повинен бути 4 або 5
    // \d{15} - після цього має йти рівно 15 цифр (загалом 16)
    // $      - кінець рядка
    const regex = /^[45]\d{15}$/;
    return regex.test(cardNumber);
}

// Перевірка роботи функції
console.log("4123456789012345:", validateCard("4123456789012345")); // true
console.log("5123456789012345:", validateCard("5123456789012345")); // true
console.log("3123456789012345:", validateCard("3123456789012345")); // false (починається з 3)
console.log("412345678901234:", validateCard("412345678901234"));   // false (15 символів)